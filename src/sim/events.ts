/**
 * 事件日志:门面输出的日志部分。
 * 每条事件带全局递增序号与发生时刻(游戏分钟),用于回放、断言与 UI 展示。
 */

export type SimEventKind =
  /** 日更:跨越游戏日边界时结算 */
  | '日更'
  /** 周更:跨越游戏周边界时结算(团本 CD 重置等) */
  | '周更'
  /** 公会:会长指令造成的状态变化 */
  | '公会'
  /** 招募:申请池刷新与招入/拒绝/淘汰(申请池见 GLOSSARY) */
  | '招募'
  /** 编成:小队成立/解散与团员调入/调离(编成见 GLOSSARY) */
  | '编成'
  /** 练级:小队进驻/撤离练级地图的会长指令(练级本身为静默计数,不产生事件) */
  | '练级'
  /** 下本:5 人本的进驻/撤离指令与逐次结算结果 + 掉落去向(结果卡 + 短日志) */
  | '下本'
  /** 团本:开团/取消安排与团本夜的逐首领结算、掉落去向与团灭代价(直播视图 + 事件日志) */
  | '团本'
  /** 经济:双钱包收支(打工/野团收入入个人金)与分配制度(换制、自肥;GLOSSARY:经济与分配) */
  | '经济'
  /** 声望:首杀入墙、里程碑达成、稀有陈列与档位/星级提升(T12,GLOSSARY:声望等级/荣誉墙) */
  | '声望'
  /** 退会:忠诚过低或长期冷板凳的自动退会,留台词与去向(T12,GLOSSARY:名人堂) */
  | '退会';

export interface SimEvent {
  /** 全局递增序号(从 1 起) */
  readonly seq: number;
  /** 发生时刻:自建会起累计的游戏分钟 */
  readonly atGameMinutes: number;
  readonly kind: SimEventKind;
  readonly text: string;
}
